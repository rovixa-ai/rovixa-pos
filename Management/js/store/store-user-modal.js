const StoreUserModal = {

    // ======================================
    // TAMBAH KASIR
    // ======================================

    openAddModal() {

        StoreUser.mode =
            "add";

        StoreUser.user =
            null;

        StoreUser.usernameAutoGenerated =
            true;

        StoreUser.generatedUsername =
            "";


        StoreUser.setModalText();


        StoreUser.setField(
            "storeUserId",
            StoreUser.generateNextId()
        );


        StoreUser.setField(
            "storeUserUsername",
            ""
        );


        StoreUser.setField(
            "storeUserName",
            ""
        );


        StoreUser.setField(
            "storeUserPin",
            ""
        );


        StoreUser.setField(
            "storeUserRole",
            "KASIR"
        );


        StoreUser.setField(
            "storeUserStatus",
            "AKTIF"
        );


        const idInput =
            document.getElementById(
                "storeUserId"
            );

        if (idInput) {

            idInput.readOnly =
                true;

        }


        const usernameInput =
            document.getElementById(
                "storeUserUsername"
            );

        if (usernameInput) {

            usernameInput.readOnly =
                false;

        }


        StoreUser.setUsernameHint(
            "Username dibuat otomatis dari nama kasir. Anda tetap dapat mengubahnya."
        );


        StoreUser.setPinHint(
            "PIN digunakan kasir untuk login."
        );


        StoreUser.message(
            "",
            "info"
        );


        StoreUser.openModal();

    },


    // ======================================
    // EDIT KASIR
    // ======================================

    openEditModal(id) {

        const user =
            StoreUser.users.find(
                item =>
                    String(
                        item?.id ||
                        ""
                    ) ===
                    String(
                        id ||
                        ""
                    )
            );


        if (!user) {

            StoreUser.showListMessage(
                "Data kasir tidak ditemukan."
            );

            return;

        }


        StoreUser.mode =
            "edit";

        StoreUser.user =
            user;

        StoreUser.usernameAutoGenerated =
            false;

        StoreUser.generatedUsername =
            "";


        StoreUser.setModalText();


        StoreUser.setField(
            "storeUserId",
            user.id || ""
        );


        StoreUser.setField(
            "storeUserUsername",
            user.username || ""
        );


        StoreUser.setField(
            "storeUserName",
            user.nama || ""
        );


        StoreUser.setField(
            "storeUserPin",
            ""
        );


        StoreUser.setField(
            "storeUserRole",
            String(
                user.role ||
                "KASIR"
            ).toUpperCase()
        );


        StoreUser.setField(
            "storeUserStatus",
            String(
                user.status ||
                "AKTIF"
            ).toUpperCase()
        );


        const idInput =
            document.getElementById(
                "storeUserId"
            );

        if (idInput) {

            idInput.readOnly =
                true;

        }


        const usernameInput =
            document.getElementById(
                "storeUserUsername"
            );

        if (usernameInput) {

            usernameInput.readOnly =
                false;

        }


        StoreUser.setUsernameHint(
            "Username dapat diubah."
        );


        StoreUser.setPinHint(
            "Kosongkan jika PIN tidak ingin diganti."
        );


        StoreUser.message(
            "",
            "info"
        );


        StoreUser.openModal();

    },


    // ======================================
    // NAMA INPUT
    // ======================================

    handleNameInput() {

        if (
            StoreUser.mode !==
            "add"
        ) {

            return;

        }


        if (
            !StoreUser.usernameAutoGenerated
        ) {

            return;

        }


        const name =
            StoreUser.value(
                "storeUserName"
            );


        const username =
            StoreUser.generateUsername(
                name
            );


        const usernameInput =
            document.getElementById(
                "storeUserUsername"
            );


        if (!usernameInput) {

            return;

        }


        usernameInput.value =
            username;


        StoreUser.generatedUsername =
            username;

    },


    // ======================================
    // USERNAME INPUT
    // ======================================

    handleUsernameInput() {

        if (
            StoreUser.mode !==
            "add"
        ) {

            return;

        }


        const usernameInput =
            document.getElementById(
                "storeUserUsername"
            );


        if (!usernameInput) {

            return;

        }


        const currentValue =
            String(
                usernameInput.value ||
                ""
            ).trim();


        if (
            currentValue ===
            StoreUser.generatedUsername
        ) {

            return;

        }


        StoreUser.usernameAutoGenerated =
            false;


        StoreUser.setUsernameHint(
            "Username diisi manual dan tidak lagi mengikuti nama kasir."
        );

    },


    // ======================================
    // GENERATE ID
    // ======================================

    generateNextId() {

        let highest =
            0;


        for (
            const user of StoreUser.users
        ) {

            const value =
                String(
                    user?.id ||
                    ""
                )
                    .trim()
                    .toUpperCase();


            const match =
                value.match(
                    /^KSR(\d+)$/
                );


            if (!match) {

                continue;

            }


            const number =
                Number(
                    match[1]
                );


            if (
                Number.isFinite(
                    number
                ) &&
                number >
                    highest
            ) {

                highest =
                    number;

            }

        }


        return (
            "KSR" +
            String(
                highest + 1
            ).padStart(
                3,
                "0"
            )
        );

    },


    // ======================================
    // GENERATE USERNAME
    // ======================================

    generateUsername(name) {

        let value =
            String(
                name ||
                ""
            )
                .trim()
                .toLowerCase();


        if (!value) {

            return "";

        }


        if (
            typeof value.normalize ===
            "function"
        ) {

            value =
                value
                    .normalize(
                        "NFD"
                    )
                    .replace(
                        /[\u0300-\u036f]/g,
                        ""
                    );

        }


        value =
            value
                .replace(
                    /[^a-z0-9]+/g,
                    "."
                )
                .replace(
                    /^\.+|\.+$/g,
                    ""
                )
                .replace(
                    /\.{2,}/g,
                    "."
                );


        if (!value) {

            return "";

        }


        const base =
            value;


        const existing =
            new Set(
                StoreUser.users
                    .map(
                        user =>
                            String(
                                user?.username ||
                                ""
                            )
                                .trim()
                                .toLowerCase()
                    )
                    .filter(Boolean)
            );


        if (
            !existing.has(
                base
            )
        ) {

            return base;

        }


        let number =
            2;


        while (
            existing.has(
                base +
                number
            )
        ) {

            number++;

        }


        return (
            base +
            number
        );

    },


    // ======================================
    // USERNAME HINT
    // ======================================

    setUsernameHint(text) {

        const element =
            document.getElementById(
                "storeUserUsernameHint"
            );


        if (!element) {

            return;

        }


        element.textContent =
            text;

    },


    // ======================================
    // PIN HINT
    // ======================================

    setPinHint(text) {

        const element =
            document.getElementById(
                "storeUserPinHint"
            );


        if (!element) {

            return;

        }


        element.textContent =
            text;

    },


    // ======================================
    // MODAL TEXT
    // ======================================

    setModalText() {

        const title =
            document.getElementById(
                "storeUserModalTitle"
            );

        const description =
            document.getElementById(
                "storeUserModalDescription"
            );

        const saveButton =
            document.getElementById(
                "storeUserSave"
            );

        const pinInput =
            document.getElementById(
                "storeUserPin"
            );


        if (
            StoreUser.mode ===
            "edit"
        ) {

            if (title) {

                title.textContent =
                    "Edit Kasir";

            }


            if (description) {

                description.textContent =
                    "Ubah data akun kasir.";

            }


            if (saveButton) {

                saveButton.textContent =
                    "Simpan Perubahan";

            }


            if (pinInput) {

                pinInput.placeholder =
                    "Masukkan PIN baru";

            }

        }
        else {

            if (title) {

                title.textContent =
                    "Tambah Kasir";

            }


            if (description) {

                description.textContent =
                    "Tambahkan akun kasir baru.";

            }


            if (saveButton) {

                saveButton.textContent =
                    "Simpan";

            }


            if (pinInput) {

                pinInput.placeholder =
                    "Masukkan PIN";

            }

        }

    },


    // ======================================
    // OPEN MODAL
    // ======================================

    openModal() {

        const modal =
            document.getElementById(
                "storeUserModal"
            );


        if (!modal) {

            return;

        }


        modal.classList.add(
            "is-open"
        );


        modal.setAttribute(
            "aria-hidden",
            "false"
        );


        document.body.classList.add(
            "store-user-modal-open"
        );


        setTimeout(
            () => {

                const target =
                    StoreUser.mode ===
                    "edit"

                        ? document.getElementById(
                            "storeUserUsername"
                        )

                        : document.getElementById(
                            "storeUserName"
                        );


                if (target) {

                    target.focus();

                }

            },
            50
        );

    },


    // ======================================
    // CLOSE MODAL
    // ======================================

    closeModal() {

        const modal =
            document.getElementById(
                "storeUserModal"
            );


        if (!modal) {

            return;

        }


        modal.classList.remove(
            "is-open"
        );


        modal.setAttribute(
            "aria-hidden",
            "true"
        );


        document.body.classList.remove(
            "store-user-modal-open"
        );


        StoreUser.message(
            "",
            "info"
        );

    },


    // ======================================
    // OPEN DELETE MODAL
    // ======================================

    openDeleteModal(id) {

        const user =
            StoreUser.users.find(
                item =>
                    String(
                        item?.id ||
                        ""
                    ) ===
                    String(
                        id ||
                        ""
                    )
            );


        if (!user) {

            return;

        }


        StoreUser.user =
            user;


        const nameElement =
            document.getElementById(
                "storeUserDeleteName"
            );

        const idElement =
            document.getElementById(
                "storeUserDeleteId"
            );


        if (nameElement) {

            nameElement.textContent =
                String(
                    user.nama ||
                    user.username ||
                    "-"
                );

        }


        if (idElement) {

            idElement.textContent =
                String(
                    user.id ||
                    "-"
                );

        }


        const modal =
            document.getElementById(
                "storeUserDeleteModal"
            );


        if (!modal) {

            return;

        }


        modal.classList.add(
            "is-open"
        );


        modal.setAttribute(
            "aria-hidden",
            "false"
        );


        document.body.classList.add(
            "store-user-modal-open"
        );

    },


    // ======================================
    // CLOSE DELETE MODAL
    // ======================================

    closeDeleteModal() {

        const modal =
            document.getElementById(
                "storeUserDeleteModal"
            );


        if (!modal) {

            return;

        }


        modal.classList.remove(
            "is-open"
        );


        modal.setAttribute(
            "aria-hidden",
            "true"
        );


        document.body.classList.remove(
            "store-user-modal-open"
        );


        StoreUser.user =
            null;

    }

};