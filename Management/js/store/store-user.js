const StoreUser = {

    // ======================================
    // STATE
    // ======================================

    users: [],

    user: null,

    mode: "add",

    usernameAutoGenerated: false,

    generatedUsername: "",


    // ======================================
    // INIT
    // ======================================

    init() {

        if (
            typeof StoreUserRender ===
            "undefined"
        ) {

            console.error(
                "STORE USER RENDER: file render belum tersedia."
            );

            return;

        }


        StoreUserRender.render();

    },


    // ======================================
    // EVENT
    // ======================================

    event() {

        StoreUserEvent.event();

    },


    // ======================================
    // LOAD USERS
    // ======================================

    async loadUsers() {

        try {

            if (
                typeof DownloadUsers ===
                "undefined"
            ) {

                throw new Error(
                    "DownloadUsers belum tersedia."
                );

            }


            const users =
                await DownloadUsers.getLocalUsers();


            StoreUser.users =
                Array.isArray(users)
                    ? users
                    : [];


            StoreUserRender.renderUsers();

        }
        catch (error) {

            console.error(
                "STORE USER LOAD ERROR:",
                error
            );


            StoreUser.showListMessage(
                error?.message ||
                "Gagal memuat data kasir."
            );

        }

    },


    // ======================================
    // REFRESH USERS
    // ======================================

    async refreshUsersAfterChange() {

        try {

            if (
                typeof DownloadUsers ===
                "undefined"
            ) {

                throw new Error(
                    "DownloadUsers belum tersedia."
                );

            }


            await DownloadUsers.download();


            const users =
                await DownloadUsers.getLocalUsers();


            StoreUser.users =
                Array.isArray(users)
                    ? users
                    : [];


            StoreUserRender.renderUsers();

        }
        catch (error) {

            console.error(
                "STORE USER REFRESH ERROR:",
                error
            );


            StoreUser.showListMessage(
                error?.message ||
                "Gagal memperbarui data kasir."
            );

        }

    },


    // ======================================
    // LIST MESSAGE
    // ======================================

    showListMessage(text) {

        StoreUserRender.showListMessage(
            text
        );

    },


    // ======================================
    // FIELD HELPER
    // ======================================

    setField(id, value) {

        const element =
            document.getElementById(
                id
            );


        if (!element) {

            return;

        }


        element.value =
            value ?? "";

    },


    value(id) {

        const element =
            document.getElementById(
                id
            );


        if (!element) {

            return "";

        }


        return String(
            element.value ??
            ""
        ).trim();

    },


    // ======================================
    // MESSAGE
    // ======================================

    message(
        text,
        type = "info"
    ) {

        const element =
            document.getElementById(
                "storeUserMessage"
            );


        if (!element) {

            return;

        }


        element.textContent =
            text || "";


        element.className =
            `store-user-message ${type}`;

    },


    // ======================================
    // MODAL DELEGATION
    // ======================================

    openAddModal() {

        StoreUserModal.openAddModal();

    },


    openEditModal(id) {

        StoreUserModal.openEditModal(
            id
        );

    },


    handleNameInput() {

        StoreUserModal.handleNameInput();

    },


    handleUsernameInput() {

        StoreUserModal.handleUsernameInput();

    },


    generateNextId() {

        return StoreUserModal.generateNextId();

    },


    generateUsername(name) {

        return StoreUserModal.generateUsername(
            name
        );

    },


    setUsernameHint(text) {

        StoreUserModal.setUsernameHint(
            text
        );

    },


    setPinHint(text) {

        StoreUserModal.setPinHint(
            text
        );

    },


    setModalText() {

        StoreUserModal.setModalText();

    },


    openModal() {

        StoreUserModal.openModal();

    },


    closeModal() {

        StoreUserModal.closeModal();

    },


    openDeleteModal(id) {

        StoreUserModal.openDeleteModal(
            id
        );

    },


    closeDeleteModal() {

        StoreUserModal.closeDeleteModal();

    },


    // ======================================
    // SAVE DELEGATION
    // ======================================

    save() {

        return StoreUserSave.save();

    },


    confirmDelete() {

        return StoreUserSave.confirmDelete();

    },


    hashPIN(pin) {

        return StoreUserSave.hashPIN(
            pin
        );

    }

};